// TestRoomDumpMatchesEngine reproduces the Zig CLI's `d2-drlg roomdump 28 0x10000000 0` output
// from the Go bindings and requires it byte for byte. The golden was produced by that CLI, so
// this is a cross-implementation check: it fails if the bindings misread the ABI, not merely if
// their own output changed.
func TestRoomDumpMatchesEngine(t *testing.T) {
	want := readGolden(t, "testdata/roomdump_28_0x10000000_0.txt")

	g := newGenerator(t)
	act, err := g.GenerateAct(0x10000000, Normal, 0)
	if err != nil {
		t.Fatal(err)
	}
	level := act.Level(28)
	if level == nil {
		t.Fatal("act I has no level 28 (Barracks)")
	}

	var b strings.Builder
	fmt.Fprintf(&b, "# level %d origin %d,%d size %dx%d rooms %d\n",
		level.ID, level.OriginX, level.OriginY, level.Width, level.Height, len(level.Rooms))
	for _, r := range level.Rooms {
		fmt.Fprintf(&b, "%d\t%d\t%d\t%d\t%d\t%d\n",
			r.X-level.OriginX, r.Y-level.OriginY, r.W, r.H, r.Kind, r.PresetKind)
	}

	if got := b.String(); got != want {
		t.Errorf("roomdump mismatch\n--- got ---\n%s\n--- want ---\n%s", got, want)
	}
}

// TestActISnapshot pins the whole shape of a generated act: every level, its metadata and the
// counts of everything read through a separate entry point. A change in any of them shows up as
// a diff of the full snapshot rather than as a passing test with different numbers.
func TestActISnapshot(t *testing.T) {
	const golden = "testdata/act1_normal_0x10000000.txt"

	g := newGenerator(t)
	act, err := g.GenerateAct(0x10000000, Normal, 0)
	if err != nil {
		t.Fatal(err)
	}

	var b strings.Builder
	fmt.Fprintf(&b, "seed 0x%08x %s act %d levels %d\n", act.Seed, act.Difficulty, act.Number+1, len(act.Levels))
	for _, l := range act.Levels {
		fmt.Fprintf(&b, "%3d %-28s %-11s placed=%v origin=%d,%d size=%dx%d rooms=%d npcs=%d objects=%d adjacents=%d\n",
			l.ID, l.Name, l.Type, l.Placed, l.OriginX, l.OriginY, l.Width, l.Height,
			len(l.Rooms), countKind(l.Presets, NPC), countKind(l.Presets, Object), len(l.Adjacents))
	}

	got := b.String()
	if *update {
		if err := os.WriteFile(golden, []byte(got), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	if want := readGolden(t, golden); got != want {
		t.Errorf("act I snapshot mismatch\n--- got ---\n%s\n--- want ---\n%s", got, want)
	}
}

// Shrines and wells are not a separate entry point: they are already among a level's presets, as
// the Objects.txt rows the outdoor spawner draws from. This is the documented way to get them,
// and the expectation is the output the root README publishes for the TypeScript binding — a
// second implementation of the same C ABI, so agreeing with it is agreement across languages.
func TestShrinesMatchPublishedExample(t *testing.T) {
	shrineRows := map[int32]string{2: "shrine", 81: "shrine", 83: "shrine", 84: "shrine", 130: "well"}

	g := newGenerator(t)
	act, err := g.GenerateAct(1337, Normal, 0)
	if err != nil {
		t.Fatal(err)
	}
	cold := act.Level(3)
	if cold == nil {
		t.Fatal("act I has no level 3 (Cold Plains)")
	}

	var got []string
	for _, p := range cold.Presets {
		if p.Kind != Object {
			continue
		}
		if kind, ok := shrineRows[p.TxtFileNo]; ok {
			// The published example reports world TILES; presets are level-local subtiles.
			got = append(got, fmt.Sprintf("%s class %d at tile (%d, %d)",
				kind, p.TxtFileNo, cold.OriginX+p.X/5, cold.OriginY+p.Y/5))
		}
	}

	want := []string{
		"shrine class 2 at tile (995, 1124)",
		"shrine class 84 at tile (994, 1114)",
		"shrine class 81 at tile (1050, 1098)",
		"well class 130 at tile (1010, 1091)",
		"shrine class 83 at tile (1002, 1090)",
	}
	if len(got) != len(want) {
		t.Fatalf("Cold Plains shrines/wells at seed 1337:\n got %v\nwant %v", got, want)
	}
	for i := range want {
		if got[i] != want[i] {
			t.Errorf("shrine %d = %q, want %q", i, got[i], want[i])
		}
	}
}

// The collision and walk grids are the two big optional copies, and the walk grid is derived
// from the collision one, so they have to agree: a cell the walk grid calls walkable must not
// carry a blocking flag in the raw CollMap.
func TestCollisionAndWalkAgree(t *testing.T) {
	g := newGenerator(t)
	act, err := g.GenerateAct(0x10000000, Normal, 0, WithCollision(), WithWalk())
	if err != nil {
		t.Fatal(err)
	}
	level := act.Level(2) // Blood Moor, an outdoor level with a real grid
	if level == nil {
		t.Fatal("act I has no level 2 (Blood Moor)")
	}
	if level.Collision == nil || level.Walk == nil {
		t.Fatalf("collision=%v walk=%v, want both", level.Collision != nil, level.Walk != nil)
	}
	if level.Collision.Width != level.Walk.Width || level.Collision.Height != level.Walk.Height {
		t.Fatalf("grid dims differ: collision %dx%d, walk %dx%d",
			level.Collision.Width, level.Collision.Height, level.Walk.Width, level.Walk.Height)
	}
	if want := level.Width * 5; level.Collision.Width != want {
		t.Errorf("collision width = %d, want the level's %d tiles in subtiles (%d)",
			level.Collision.Width, level.Width, want)
	}

	// The mask the walk grid is derived with: blocked terrain, player-blocked, or an object.
	const blocking = Wall | NoPlayer | ObjectBit
	walkable := 0
	for y := int32(0); y < level.Walk.Height; y++ {
		for x := int32(0); x < level.Walk.Width; x++ {
			c := level.Collision.At(x, y)
			if !level.Walk.At(x, y) {
				continue
			}
			walkable++
			if c == Void || c&blocking != 0 {
				t.Fatalf("subtile %d,%d is walkable but its CollMap cell is 0x%04x", x, y, c)
			}
		}
	}
	if walkable == 0 {
		t.Error("no walkable subtile in the Blood Moor")
	}
}

// A generator with no act generated still answers table lookups, and a closed one answers
// nothing. Close is idempotent because a deferred Close after an explicit one is normal Go.
func TestLifecycle(t *testing.T) {
	g, err := New()
	if err != nil {
		t.Fatal(err)
	}
	if got := g.levelName(1); got != "Rogue Encampment" {
		t.Errorf("levelName(1) = %q, want %q", got, "Rogue Encampment")
	}
	if g.Core() == 0 {
		t.Error("Core() on an open generator is 0")
	}
	if err := g.Close(); err != nil {
		t.Fatal(err)
	}
	if err := g.Close(); err != nil {
		t.Fatalf("second Close: %v", err)
	}
	if g.Core() != 0 {
		t.Error("Core() on a closed generator is not 0")
	}
	if _, err := g.GenerateAct(1, Normal, 0); err != ErrClosed {
		t.Errorf("GenerateAct after Close = %v, want %v", err, ErrClosed)
	}
}

