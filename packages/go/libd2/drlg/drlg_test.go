// update rewrites the goldens this package generates itself. It deliberately does NOT touch
// testdata/roomdump_*, which comes from the Zig CLI: a golden the bindings can rewrite is a
// golden that cannot catch them being wrong.
var update = flag.Bool("update", false, "rewrite the goldens generated by these bindings")

// The generated structs are filled by the native side in place, so their layout is the ABI.
// These are the sizes and offsets d2drlg.h defines; a mismatch means every list read is garbage.
func TestStructLayout(t *testing.T) {
	if got, want := unsafe.Sizeof(Room{}), uintptr(28); got != want {
		t.Errorf("sizeof(Room) = %d, want %d", got, want)
	}
	for _, c := range []struct {
		field string
		got   uintptr
		want  uintptr
	}{
		{"Room.X", unsafe.Offsetof(Room{}.X), 0},
		{"Room.Y", unsafe.Offsetof(Room{}.Y), 4},
		{"Room.W", unsafe.Offsetof(Room{}.W), 8},
		{"Room.H", unsafe.Offsetof(Room{}.H), 12},
		{"Room.Kind", unsafe.Offsetof(Room{}.Kind), 16},
		{"Room.PresetKind", unsafe.Offsetof(Room{}.PresetKind), 20},
		{"Room.PickedFile", unsafe.Offsetof(Room{}.PickedFile), 24},
	} {
		if c.got != c.want {
			t.Errorf("offsetof(%s) = %d, want %d", c.field, c.got, c.want)
		}
	}

	if got, want := unsafe.Sizeof(PresetUnit{}), uintptr(16); got != want {
		t.Errorf("sizeof(PresetUnit) = %d, want %d", got, want)
	}
	if got, want := unsafe.Offsetof(PresetUnit{}.TxtFileNo), uintptr(4); got != want {
		t.Errorf("offsetof(PresetUnit.TxtFileNo) = %d, want %d", got, want)
	}
	if got, want := unsafe.Sizeof(Adjacent{}), uintptr(12); got != want {
		t.Errorf("sizeof(Adjacent) = %d, want %d", got, want)
	}
}

