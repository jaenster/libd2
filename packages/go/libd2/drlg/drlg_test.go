// All five acts generate, which is the cheapest guard against a level index the bindings walk
// off the end of.
func TestAllActs(t *testing.T) {
	g := newGenerator(t)
	for act := 0; act < 5; act++ {
		a, err := g.GenerateAct(0x10000000, Hell, act)
		if err != nil {
			t.Fatalf("act %d: %v", act+1, err)
		}
		if len(a.Levels) == 0 {
			t.Fatalf("act %d generated no levels", act+1)
		}
		for _, l := range a.Levels {
			if l.ID <= 0 {
				t.Fatalf("act %d has a level with id %d", act+1, l.ID)
			}
		}
	}
}

// One generator per goroutine is the documented way to parallelise, and it is also the case
// that would show up any trouble with calling into the library from several OS threads at once —
// purego has no cgo call boundary doing that for us.
func TestConcurrentGenerators(t *testing.T) {
	want, err := newGenerator(t).GenerateAct(0x10000000, Normal, 0)
	if err != nil {
		t.Fatal(err)
	}

	const workers = 8
	errs := make(chan error, workers)
	for i := 0; i < workers; i++ {
		go func() {
			g, err := New()
			if err != nil {
				errs <- err
				return
			}
			defer g.Close()
			got, err := g.GenerateAct(0x10000000, Normal, 0)
			if err != nil {
				errs <- err
				return
			}
			if len(got.Levels) != len(want.Levels) {
				errs <- fmt.Errorf("generated %d levels, want %d", len(got.Levels), len(want.Levels))
				return
			}
			for i := range want.Levels {
				if got.Levels[i].ID != want.Levels[i].ID ||
					len(got.Levels[i].Rooms) != len(want.Levels[i].Rooms) {
					errs <- fmt.Errorf("level %d differs from the single-threaded generation", want.Levels[i].ID)
					return
				}
			}
			errs <- nil
		}()
	}
	for i := 0; i < workers; i++ {
		if err := <-errs; err != nil {
			t.Error(err)
		}
	}
}

// What a whole act costs, which is the only number that matters for choosing between calling the
// native library and not: generation itself dominates, and the per-call FFI overhead does not
// show up at this granularity.
