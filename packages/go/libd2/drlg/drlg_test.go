// A single trivial call, to price the FFI boundary itself.
func BenchmarkABIVersion(b *testing.B) {
	a, err := load()
	if err != nil {
		b.Fatal(err)
	}
	for b.Loop() {
		_ = a.abiVersion()
	}
}

func countKind(units []PresetUnit, kind PresetKind) int {
	n := 0
	for _, u := range units {
		if u.Kind == kind {
			n++
		}
	}
	return n
}

func newGenerator(t *testing.T) *Generator {
	t.Helper()
	g, err := New()
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { g.Close() })
	return g
}

func readGolden(t *testing.T, path string) string {
	t.Helper()
	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}
