//! Storm's adaptive Huffman decoder — the `0x01` bit of an MPQ sector's compression mask.
//!
//! A stream opens with one byte naming which of nine built-in weight tables to start from. The
//! table seeds a Huffman tree over 0x102 symbols: the 256 byte values plus 0x100 (end of stream)
//! and 0x101 (an escape, followed by a raw 8-bit byte that is then grafted into the tree). The
//! tree stays adaptive: symbol weights rise as the stream is read and nodes swap positions to
//! keep the list ordered, so the same code means different things at different points in a
//! stream. Every step below tracks Storm's own, because the codes only line up if it does.
//!
//! The tree is a doubly linked list of nodes ordered by descending weight, threaded with parent
//! and child links. The list head is the root; the tail is the lightest leaf. A node's two
//! children are `child` and `child.prev`, which is why list order and tree shape cannot be
//! separated — moving a node in the list re-parents it.

const std = @import("std");

pub const Error = error{ Truncated, BadTree };

/// 0x102 leaves and the 0x101 interior nodes that join them: the most a tree can ever hold, and
/// exactly what the escape path can grow it to, since each escape adds one leaf and one interior.
const max_nodes: u16 = 0x203;
const nil: u16 = 0xFFFF;
/// The list terminator, stored one past the node array so it links like any other node.
const sentinel: u16 = max_nodes;

const Node = struct {
    value: u16 = 0,
    weight: u32 = 0,
    child: u16 = nil,
    parent: u16 = nil,
    next: u16 = nil,
    prev: u16 = nil,
};

/// A stream is read a bit at a time from the low end, but refilled in 16- and 32-bit gulps —
/// the two refills interleave, so both are kept exactly as Storm has them.
const Bits = struct {
    src: []const u8,
    pos: usize = 0,
    buf: u32 = 0,
    cnt: i32 = 0,

    fn take(self: *Bits, n: usize) u32 {
        var v: u32 = 0;
        for (0..n) |i| {
            const b: u32 = if (self.pos + i < self.src.len) self.src[self.pos + i] else 0;
            v |= b << @intCast(i * 8);
        }
        self.pos += n;
        return v;
    }

    fn byte(self: *Bits) u32 {
        if (self.cnt <= 8) {
            self.buf |= self.take(2) << @intCast(self.cnt);
            self.cnt += 16;
        }
        const v = self.buf & 0xFF;
        self.cnt -= 8;
        self.buf >>= 8;
        return v;
    }

    /// Storm tops the buffer up before every symbol so the tree walk never has to.
    fn top(self: *Bits) void {
        if (self.cnt <= 7) {
            self.buf |= self.take(2) << @intCast(self.cnt);
            self.cnt += 16;
        }
    }

    fn bit(self: *Bits) u1 {
        const b: u1 = @intCast(self.buf & 1);
        self.buf >>= 1;
        self.cnt -= 1;
        if (self.cnt == 0) {
            self.buf = self.take(4);
            self.cnt = 32;
        }
        return b;
    }
};

const Tree = struct {
    nodes: [max_nodes + 1]Node,
    used: u16,
    by_value: [0x102]u16,
    /// The heaviest weight placed so far. A node at or above it goes straight to the head, which
    /// is where the ordering's tie-breaking comes from: an equal weight lands ahead of its peers.
    max_weight: u32,

    fn n(self: *Tree, i: u16) *Node {
        return &self.nodes[i];
    }

    fn init(self: *Tree, comp_type: u8) Error!void {
        if (comp_type >= weights.len) return Error.BadTree;
        self.nodes = @splat(.{});
        self.used = 0;
        self.by_value = @splat(nil);
        self.max_weight = 0;
        self.nodes[sentinel] = .{ .next = sentinel, .prev = sentinel };

        const table = &weights[comp_type];
        for (0..0x100) |i| {
            if (table[i] == 0) continue;
            const at = try self.leaf(@intCast(i), table[i]);
            self.place(at, nil);
        }
        // End-of-stream and escape are not in the tables; Storm appends them at weight 1, which
        // is below every table weight, so the tail of the list is always one of these two.
        for (0x100..0x102) |v| {
            const at = try self.leaf(@intCast(v), 1);
            self.linkAfter(self.n(sentinel).prev, at);
        }
        try self.build();
    }

    /// Interior nodes carry no symbol, so only a leaf is recorded in `by_value`.
    fn leaf(self: *Tree, value: u16, weight: u32) Error!u16 {
        const at = try self.alloc(value, weight);
        self.by_value[value] = at;
        return at;
    }

    fn alloc(self: *Tree, value: u16, weight: u32) Error!u16 {
        if (self.used >= max_nodes) return Error.BadTree;
        const at = self.used;
        self.used += 1;
        self.nodes[at] = .{ .value = value, .weight = weight };
        return at;
    }

    fn unlink(self: *Tree, at: u16) void {
        const node = self.n(at);
        if (node.next == nil) return;
        self.n(node.prev).next = node.next;
        self.n(node.next).prev = node.prev;
        node.next = nil;
        node.prev = nil;
    }

    /// Put `at` directly behind `after`; `nil` means the head of the list.
    fn linkAfter(self: *Tree, after: u16, at: u16) void {
        const ref = if (after == nil) sentinel else after;
        const nxt = self.n(ref).next;
        self.n(at).next = nxt;
        self.n(at).prev = ref;
        self.n(nxt).prev = at;
        self.n(ref).next = at;
    }

    /// Insert by weight, descending. `from` is where the backward scan starts — the tail unless
    /// the caller already knows nothing behind a given node can outweigh the newcomer.
    fn place(self: *Tree, at: u16, from: u16) void {
        self.unlink(at);
        self.linkAfter(nil, at);
        const w = self.n(at).weight;
        if (w >= self.max_weight) {
            self.max_weight = w;
            return;
        }
        self.unlink(at);
        var c = if (from == nil) self.n(sentinel).prev else from;
        while (c != sentinel and self.n(c).weight < w) c = self.n(c).prev;
        self.linkAfter(if (c == sentinel) nil else c, at);
    }

    /// Join the two lightest nodes under a new parent, over and over, until one node is left.
    /// Pairs stay in the list where they are, so the parent's `child.prev` keeps naming the
    /// sibling; only nodes ahead of the pair are ever disturbed.
    fn build(self: *Tree) Error!void {
        var cur = self.n(sentinel).prev;
        while (cur != sentinel) {
            const a = self.n(cur).prev;
            if (a == sentinel) break;
            const parent = try self.alloc(0, self.n(a).weight + self.n(cur).weight);
            self.n(parent).child = cur;
            self.n(a).parent = parent;
            self.n(cur).parent = parent;
            // The parent outweighs both children, so nothing behind `a` can hold it.
            self.place(parent, self.n(a).prev);
            cur = self.n(a).prev;
        }
    }

    fn root(self: *Tree) u16 {
        return self.n(sentinel).next;
    }

    /// One more sighting of a symbol. The node rises past every lighter node ahead of it,
    /// swapping places — and parents — with the last one it passes, then its parent does the same.
    fn adjust(self: *Tree, start: u16) void {
        var item = start;
        while (item != nil) {
            self.n(item).weight += 1;
            const w = self.n(item).weight;

            var at = item;
            var stop: u16 = nil;
            while (true) {
                const p = self.n(at).prev;
                if (p == sentinel or p == nil) {
                    stop = nil;
                    break;
                }
                if (self.n(p).weight >= w) {
                    stop = p;
                    break;
                }
                at = p;
            }

            if (at != item) {
                self.unlink(at);
                self.linkAfter(item, at);
                self.unlink(item);
                self.linkAfter(stop, item);

                // Both reparent checks read the tree as it was: when the two are siblings, the
                // first write would otherwise make the second one fire as well.
                const ip = self.n(item).parent;
                const ap = self.n(at).parent;
                const ip_owns = ip != nil and self.n(ip).child == item;
                const ap_child = if (ap != nil) self.n(ap).child else nil;
                if (ip_owns) self.n(ip).child = at;
                if (ap_child == at) self.n(ap).child = item;
                self.n(item).parent = ap;
                self.n(at).parent = ip;
            }
            item = self.n(item).parent;
        }
    }

    /// Graft a byte the tree has never seen onto its lightest leaf: that leaf becomes an interior
    /// node holding a copy of itself and the newcomer.
    fn graft(self: *Tree, value: u8) Error!u16 {
        const old = self.n(sentinel).prev;
        if (old == sentinel) return Error.BadTree;

        const clone = try self.leaf(self.n(old).value, self.n(old).weight);
        self.linkAfter(self.n(sentinel).prev, clone);
        self.n(clone).parent = old;

        const fresh = try self.leaf(value, 0);
        self.linkAfter(self.n(sentinel).prev, fresh);
        self.n(fresh).parent = old;

        self.n(old).child = fresh;
        self.adjust(fresh);
        return fresh;
    }
};

/// Expand one Huffman-coded chunk. Stops at the stream's end marker or when `dst` is full,
/// whichever comes first, and returns how much was written.
pub fn decompress(dst: []u8, src: []const u8) Error!usize {
    if (dst.len == 0) return 0;
    if (src.len == 0) return Error.Truncated;

    var bits = Bits{ .src = src };
    const comp_type: u8 = @intCast(bits.byte());
    var tree: Tree = undefined;
    try tree.init(comp_type);
    // Only the table-0 stream keeps re-weighting on ordinary symbols; the others re-weight only
    // around a graft. The two are exclusive, and swapping them scrambles the codes.
    const rolling = comp_type == 0;

    var out: usize = 0;
    while (out < dst.len) {
        bits.top();
        var at = tree.root();
        while (true) {
            at = tree.n(at).child;
            if (at == nil) return Error.BadTree;
            if (bits.bit() == 1) {
                at = tree.n(at).prev;
                if (at == sentinel or at == nil) return Error.BadTree;
            }
            if (tree.n(at).child == nil) break;
        }

        var value = tree.n(at).value;
        if (value == 0x101) {
            value = @intCast(bits.byte());
            const fresh = try tree.graft(@intCast(value));
            if (!rolling) tree.adjust(fresh);
        }
        if (value == 0x100) break;

        dst[out] = @intCast(value);
        out += 1;
        if (rolling and tree.by_value[value] != nil) tree.adjust(tree.by_value[value]);
    }
    return out;
}

