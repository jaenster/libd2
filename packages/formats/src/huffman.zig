const testing = std.testing;

/// Walk the finished tree and report how many leaves it holds and how deep the deepest code is,
/// failing on any structure a decoder could not walk.
fn survey(tree: *Tree, at: u16, depth: u32, leaves: *u32, deepest: *u32) !void {
    try testing.expect(at != nil and at != sentinel);
    const child = tree.n(at).child;
    if (child == nil) {
        leaves.* += 1;
        deepest.* = @max(deepest.*, depth);
        return;
    }
    const other = tree.n(child).prev;
    try testing.expect(other != sentinel and other != nil);
    try testing.expect(other != child);
    try testing.expectEqual(at, tree.n(child).parent);
    try testing.expectEqual(at, tree.n(other).parent);
    try testing.expectEqual(tree.n(at).weight, tree.n(child).weight + tree.n(other).weight);
    try survey(tree, child, depth + 1, leaves, deepest);
    try survey(tree, other, depth + 1, leaves, deepest);
}

test "huffman: every built-in table yields a walkable tree over its symbols" {
    for (0..weights.len) |t| {
        var tree: Tree = undefined;
        try tree.init(@intCast(t));

        var want: u32 = 2; // end-of-stream and escape are always added
        for (weights[t][0..0x100]) |w| {
            if (w != 0) want += 1;
        }

        var leaves: u32 = 0;
        var deepest: u32 = 0;
        try survey(&tree, tree.root(), 0, &leaves, &deepest);
        try testing.expectEqual(want, leaves);
        // A code no longer than the symbol count is the loosest bound that still catches a tree
        // that looped back on itself.
        try testing.expect(deepest <= 0x102);
        // The list runs heaviest first, which is what makes the head the root.
        var at = tree.root();
        while (tree.n(at).next != sentinel) : (at = tree.n(at).next) {
            try testing.expect(tree.n(at).weight >= tree.n(tree.n(at).next).weight);
        }
    }
}

test "huffman: an escape grafts the new byte onto the lightest leaf" {
    var tree: Tree = undefined;
    try tree.init(7);
    const before = tree.used;
    const lightest = tree.n(sentinel).prev;
    const lightest_value = tree.n(lightest).value;

    const fresh = try tree.graft(0xAB);
    try testing.expectEqual(before + 2, tree.used);
    try testing.expectEqual(@as(u16, 0xAB), tree.n(fresh).value);
    // The old leaf is now an interior node, and the byte it stood for lives on in the copy.
    try testing.expect(tree.n(lightest).child != nil);
    try testing.expect(tree.by_value[lightest_value] != lightest);
    try testing.expectEqual(lightest_value, tree.n(tree.by_value[lightest_value]).value);

    var leaves: u32 = 0;
    var deepest: u32 = 0;
    try survey(&tree, tree.root(), 0, &leaves, &deepest);
}

test "huffman: a truncated stream stops at the end of its input" {
    var dst: [64]u8 = undefined;
    // A type byte and nothing else: the walk runs off the end of the input, which reads as zeros.
    const n = decompress(&dst, &[_]u8{7}) catch |err| {
        try testing.expect(err == Error.BadTree);
        return;
    };
    try testing.expect(n <= dst.len);
}
